create table authentication_credentials (
 identity_id uuid primary key references ima_identities(id) on delete cascade,
 password_hash varchar(100), failures integer not null default 0 check(failures>=0),locked_until timestamptz,
 enabled boolean not null default true,created_at timestamptz not null,updated_at timestamptz not null
);
create table authentication_challenges (
 id uuid primary key,identity_id uuid not null references ima_identities(id) on delete cascade,
 purpose varchar(30) not null check(purpose in ('ACCOUNT_ACTIVATION','PASSWORD_RESET')),
 token_hash varchar(64) not null unique,created_at timestamptz not null,expires_at timestamptz not null,
 consumed_at timestamptz,check(expires_at>created_at)
);
create index idx_challenge_identity on authentication_challenges(identity_id,purpose);
create table authentication_audit (id bigint generated by default as identity primary key,identity_id uuid,event varchar(60) not null,occurred_at timestamptz not null);
create table authentication_rate_limits (bucket varchar(64) primary key,window_start timestamptz not null,attempts integer not null);
create table authentication_notification_jobs (id uuid primary key,identity_id uuid not null references ima_identities(id) on delete cascade,purpose varchar(30) not null,attempts integer not null default 0,next_attempt_at timestamptz not null,delivered_at timestamptz);
create table authentication_bootstrap (name varchar(50) primary key,identity_id uuid not null,completed_at timestamptz not null);

create unique index uk_notification_pending on authentication_notification_jobs(identity_id,purpose) where delivered_at is null;
create index idx_notification_due on authentication_notification_jobs(next_attempt_at) where delivered_at is null;
